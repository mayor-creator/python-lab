locations = [
    "San Diego",
    "Osaka",
    "Houston",
    "New Orleans",
    "Paris",
    "London",
    "Tokyo",
    "Barcelona",
    "New York City",
    "Kyoto",
]
print(f"Original location list: {locations}")

location_sort = sorted(locations)
print(f"Sort location list: {location_sort}")

reverse_sort = sorted(locations, reverse=True)
print(f"Reverse sort location list: {reverse_sort}")
